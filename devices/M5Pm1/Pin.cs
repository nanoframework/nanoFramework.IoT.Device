namespace Iot.Device.M5Pm1
{
    /// <summary>
    /// Identifies one of the M5PM1 general-purpose I/O pins.
    /// </summary>
    public enum Pin
    {
        /// <summary>
        /// GPIO pin 0.
        /// </summary>
        Gpio0 = 0,

        /// <summary>
        /// GPIO pin 1.
        /// </summary>
        Gpio1 = 1,

        /// <summary>
        /// GPIO pin 2.
        /// </summary>
        Gpio2 = 2,

        /// <summary>
        /// GPIO pin 3.
        /// </summary>
        Gpio3 = 3,

        /// <summary>
        /// GPIO pin 4.
        /// </summary>
        Gpio4 = 4,
    }
}
